/** Match both the explicit synthetic model ID and its supplied threat inventory. */
export function getThreatFixtures(card) {
  if (!card || typeof card !== 'object' || Array.isArray(card)
    || card.synthetic !== true || typeof card.id !== 'string' || !Array.isArray(card.threats)) return [];
  const threatIds = new Set(card.threats.filter((threat) => threat
    && typeof threat === 'object' && !Array.isArray(threat) && typeof threat.id === 'string')
    .map((threat) => threat.id));
  return threatFixtures.filter((fixture) => fixture.modelId === card.id && threatIds.has(fixture.threatId));
}
