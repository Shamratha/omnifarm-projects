#!/usr/bin/env python3
"""Generate a deterministic synthetic event dataset for render-load checks.

The generated records are deliberately geometric test data, not a physics
simulation. Fixed dimensions give 320 tracks and 20,480 events, exceeding a
20,000-event test budget while remaining small enough for local tests and git.
This budget is a fixture target, not a claim about the browser's current cap.

Examples:
    python scripts/generate_render_fixture.py --output /tmp/render-load.json
    python scripts/generate_render_fixture.py --format csv \
        --output fixtures/synthetic-render-load.csv
"""

import argparse
import csv
import json
from pathlib import Path

if __package__:
    from .import_tracks import validate_document
else:
    from import_tracks import validate_document


DEFAULT_TRACK_COUNT = 320
DEFAULT_EVENTS_PER_TRACK = 64
RENDER_EVENT_BUDGET = 20_000
CSV_FIELDS = (
    "ion_id", "parent_id", "species", "kind", "event_type", "time_fs",
    "x_nm", "y_nm", "z_nm", "deposited_energy_ev",
)


def build_document():
    """Return deterministic, bounded synthetic trajectory data."""
    root_count = 8
    tracks = []
    for track_index in range(DEFAULT_TRACK_COUNT):
        ion_id = track_index + 1
        is_primary = track_index < root_count
        parent_id = None if is_primary else (track_index % root_count) + 1
        kind = "primary" if is_primary else "recoil"
        species = "Ar" if is_primary else "Si"
        events = []
        for event_index in range(DEFAULT_EVENTS_PER_TRACK):
            event_type = ("ionization", "collision", "scattering", "termination")[
                event_index % 4
            ]
            events.append({
                "timeFs": event_index * 4 + track_index % 3,
                "positionNm": [
                    ((track_index * 13 + event_index * 7) % 100) - 50,
                    ((track_index * 17 + event_index * 11) % 100) - 50,
                    event_index * 160 // (DEFAULT_EVENTS_PER_TRACK - 1),
                ],
                "depositedEnergyEv": 1 + (event_index * 7 + track_index) % 240,
                "eventType": event_type,
            })
        tracks.append({
            "ionId": ion_id,
            "parentId": parent_id,
            "species": species,
            "kind": kind,
            "events": events,
        })

    return {
        "metadata": {
            "name": "Synthetic render-load fixture",
            "description": (
                "Deterministic geometric records for exercising bounded rendering "
                "and event-type import. This is synthetic test data, not a physics simulation."
            ),
            "source": "Generated by scripts/generate_render_fixture.py",
            "ion": "Synthetic ions",
            "material": "Synthetic target",
            "incidentEnergyKeV": 30,
            "targetSizeNm": [100, 100, 160],
        },
        "tracks": tracks,
    }


def write_json(document, output):
    with Path(output).open("w", encoding="utf-8") as handle:
        json.dump(document, handle, indent=2, allow_nan=False)
        handle.write("\n")


def write_csv(document, output):
    with Path(output).open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=CSV_FIELDS, lineterminator="\n")
        writer.writeheader()
        for track in document["tracks"]:
            for event in track["events"]:
                writer.writerow({
                    "ion_id": track["ionId"],
                    "parent_id": "" if track["parentId"] is None else track["parentId"],
                    "species": track["species"],
                    "kind": track["kind"],
                    "event_type": event["eventType"],
                    "time_fs": event["timeFs"],
                    "x_nm": event["positionNm"][0],
                    "y_nm": event["positionNm"][1],
                    "z_nm": event["positionNm"][2],
                    "deposited_energy_ev": event["depositedEnergyEv"],
                })


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--format", choices=("json", "csv"), default="json")
    args = parser.parse_args(argv)
    document = build_document()
    validate_document(document)
    if args.format == "json":
        write_json(document, args.output)
    else:
        write_csv(document, args.output)
    event_count = sum(len(track["events"]) for track in document["tracks"])
    print(f"Generated {args.output} ({len(document['tracks'])} tracks, {event_count} events)")


if __name__ == "__main__":
    main()
