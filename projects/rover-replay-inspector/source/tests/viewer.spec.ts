test('exact report preview matches downloads across policy, frame, tab, and filter changes', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('tab', { name: /Policy comparison/ }).click();
  await page.getByRole('button', { name: 'Preview exact JSON' }).click();
  const preview = await page.getByLabel('Exact report JSON preview').textContent();
  const pending = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download inspection JSON' }).click();
  const download = await pending;
  const stream = await download.createReadStream();
  const chunks: Buffer[] = [];
  for await (const chunk of stream!) chunks.push(chunk);
  const first = Buffer.concat(chunks).toString('utf8');
  expect(first).toBe(preview);
  expect(first.endsWith('\n')).toBe(true);
  const report = JSON.parse(first);
  expect(report.summaries.map((entry: { id: string }) => entry.id)).toEqual(['baseline', 'ppo', 'sac']);
  expect(report.traces.map((entry: { id: string }) => entry.id)).toEqual(['baseline', 'ppo', 'sac']);
  expect(report.ranking.map((entry: { id: string; rank: number }) => [entry.id, entry.rank])).toEqual([['sac', 1], ['ppo', 2], ['baseline', 3]]);
  expect(report.summaries[0].summary).toMatchObject({ completionStatus: 'partial', completedGoals: 2, remainingGoals: 1, safetyStatus: 'unsafe', contacts: 2, unsafeFrames: 2 });
  expect(report.summaries[1].summary.eventCounts).toEqual({ contact: 2, staleObservation: 1, clearance: 2 });
  expect(report.summaries[1].evidence.map((entry: { frameIndex: number }) => entry.frameIndex)).toEqual([48, 49]);
  expect(report.summaries[1].evidence[0].decision).toMatchObject({ decisionTime: 24, observationTime: 23.1, observationAgeMs: 900 });
  expect(report.summaries[1].evidence[0].events.map((event: { type: string }) => event.type)).toEqual(['contact', 'stale-observation', 'clearance']);
  for (const ranking of report.ranking) {
    const row = page.locator(`.policy-comparison-table tr[data-policy-id="${ranking.id}"]`);
    await expect(row.locator('.table-number')).toHaveText(ranking.totalReward.toFixed(2));
  }
  await page.getByLabel('ACTIVE POLICY').selectOption('sac');
  await page.getByRole('tab', { name: /Replay overview/ }).click();
  await page.getByRole('button', { name: 'Restart replay' }).click();
  await page.getByRole('button', { name: 'Play replay' }).click();
  await expect(page.getByRole('slider')).not.toHaveValue('0');
  await page.getByRole('button', { name: 'Pause replay' }).click();
  await page.getByRole('tab', { name: /Event log/ }).click();
  await page.getByLabel('Filter event type').selectOption('stale-observation');
  const next = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export report' }).click();
  const second = await next;
  const secondStream = await second.createReadStream();
  const secondChunks: Buffer[] = [];
  for await (const chunk of secondStream!) secondChunks.push(chunk);
  expect(Buffer.concat(secondChunks).toString('utf8')).toBe(first);
});

